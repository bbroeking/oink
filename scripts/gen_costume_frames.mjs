#!/usr/bin/env node
// Costume skins (Halloween 2026): scan assets/images/sprites/costumes/<slug>/
// and emit constants/costumeFrames.generated.ts, the costume hat id ->
// { frameName: require(...) } map PigStage swaps in for Rosie's own frames.
//
// A skin is emitted only when it is COMPLETE: all six families, four frames
// each (idle, happy, surprise front; face, face_sit, walk turned/side), so a
// costumed pig never falls back to un-costumed Rosie mid-animation. Extra
// frames that follow the same `<family>_<n>.png` naming ride along. A costume
// with no emitted skin is unavailable on the client (utils/costumeFit.ts).
//
// Usage: node scripts/gen_costume_frames.mjs [--check]
//   --check exits 1 if the generated file is stale (for CI / pre-freeze).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SKINS_DIR = path.join(ROOT, "assets/images/sprites/costumes");
const OUT = path.join(ROOT, "constants/costumeFrames.generated.ts");

export const REQUIRED_FAMILIES = ["idle", "happy", "surprise", "face", "face_sit", "walk"];
export const FRAMES_PER_FAMILY = 4;
const FRAME_FILE = /^([a-z]+(?:_[a-z]+)*)_(\d+)\.png$/;

/** `hollow-jack` -> `halloween_2026_hollow_jack_costume` (the hats row id). */
export function costumeIdForSlug(slug) {
	return `halloween_2026_${slug.replace(/-/g, "_")}_costume`;
}

/** Frame names (sorted) a skin directory holds, from its file list. */
export function frameNamesFrom(files) {
	return files
		.map((file) => FRAME_FILE.exec(file))
		.filter(Boolean)
		.map((m) => ({ name: `${m[1]}_${Number(m[2])}`, family: m[1], n: Number(m[2]) }))
		.sort((a, b) => (a.family === b.family ? a.n - b.n : a.family < b.family ? -1 : 1))
		.map((f) => f.name);
}

/** The required frames a skin is missing (empty = complete). */
export function missingFrames(names) {
	const have = new Set(names);
	const missing = [];
	for (const family of REQUIRED_FAMILIES) {
		for (let n = 1; n <= FRAMES_PER_FAMILY; n += 1) {
			if (!have.has(`${family}_${n}`)) missing.push(`${family}_${n}`);
		}
	}
	return missing;
}

/** { costumeId: { slug, frames: [{name, file}] } } for every complete skin. */
export function scanSkins(dir = SKINS_DIR) {
	const complete = {};
	const incomplete = {};
	if (!fs.existsSync(dir)) return { complete, incomplete };
	for (const slug of fs.readdirSync(dir).sort()) {
		const skinDir = path.join(dir, slug);
		if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || !fs.statSync(skinDir).isDirectory()) continue;
		const files = fs.readdirSync(skinDir);
		const names = frameNamesFrom(files);
		const missing = missingFrames(names);
		if (missing.length > 0) {
			incomplete[slug] = missing;
			continue;
		}
		const byName = new Map(
			files.flatMap((file) => {
				const m = FRAME_FILE.exec(file);
				return m ? [[`${m[1]}_${Number(m[2])}`, file]] : [];
			}),
		);
		complete[costumeIdForSlug(slug)] = {
			slug,
			frames: names.map((name) => ({ name, file: byName.get(name) })),
		};
	}
	return { complete, incomplete };
}

export function render(complete) {
	const lines = [
		"/* eslint-disable @typescript-eslint/no-require-imports */",
		"// Generated by scripts/gen_costume_frames.mjs. Do not edit by hand.",
		"// Costume skins: Rosie wearing each full costume, drawn on her own 370x383",
		"// canvas (same scale, camera and baseline), swapped in for her frames by",
		"// PigStage. Only complete skins (idle, happy, surprise, face, face_sit, walk;",
		"// four frames each) are listed; a costume missing here is unavailable.",
		"export const COSTUME_FRAMES: Readonly<Record<string, Readonly<Record<string, number>>>> = {",
	];
	for (const id of Object.keys(complete).sort()) {
		const { slug, frames } = complete[id];
		lines.push(`\t${id}: {`);
		for (const { name, file } of frames) {
			lines.push(`\t\t${name}: require("../assets/images/sprites/costumes/${slug}/${file}"),`);
		}
		lines.push("\t},");
	}
	lines.push("};", "");
	return lines.join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
	const { complete, incomplete } = scanSkins();
	const text = render(complete);
	const check = process.argv.includes("--check");
	const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
	if (check) {
		if (current !== text) {
			console.error("constants/costumeFrames.generated.ts is stale; run node scripts/gen_costume_frames.mjs");
			process.exit(1);
		}
	} else if (current !== text) {
		fs.writeFileSync(OUT, text);
	}
	const ids = Object.keys(complete);
	console.log(`costume skins emitted: ${ids.length}${ids.length ? ` (${ids.map((id) => complete[id].slug).join(", ")})` : ""}`);
	for (const [slug, missing] of Object.entries(incomplete)) {
		console.log(`  skipped ${slug}: missing ${missing.length} (${missing.slice(0, 6).join(", ")}${missing.length > 6 ? ", ..." : ""})`);
	}
}
