#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const names = ["bless", "curse", "visit", "pin"];
const root = process.cwd();
const sourceDir = path.join(root, "assets/icons/friend-actions");
const outputPath = path.join(root, "constants/friendActionIcons.generated.ts");

function validate(name, svg) {
	if (!/^\s*<svg\b/i.test(svg) || !/<\/svg>\s*$/i.test(svg)) {
		throw new Error(`${name}.svg must have an <svg> root`);
	}
	if (!/\bviewBox\s*=\s*["'][^"']+["']/i.test(svg)) {
		throw new Error(`${name}.svg must declare a viewBox`);
	}
	const forbidden = [
		[/<\s*image\b/i, "embedded images"],
		[/\bdata\s*:/i, "data URLs"],
		[/<\s*text\b/i, "text"],
		[/<\s*filter\b|\bfilter\s*=/i, "filters"],
		[/\b(?:href|xlink:href)\s*=|\burl\s*\(/i, "external references"],
	];
	for (const [pattern, label] of forbidden) {
		if (pattern.test(svg)) throw new Error(`${name}.svg contains forbidden ${label}`);
	}
	if (/<!DOCTYPE|<!ENTITY|<\s*(?:script|style|foreignObject)\b/i.test(svg)) {
		throw new Error(`${name}.svg contains non-vector markup`);
	}
	const vectorElements = new Set([
		"svg", "g", "path", "rect", "circle", "ellipse", "line", "polyline", "polygon",
	]);
	for (const match of svg.matchAll(/<\/?\s*([A-Za-z][\w:-]*)\b/g)) {
		if (!vectorElements.has(match[1])) {
			throw new Error(`${name}.svg contains unsupported <${match[1]}> markup`);
		}
	}
}

const entries = [];
for (const name of names) {
	const svg = (await readFile(path.join(sourceDir, `${name}.svg`), "utf8")).trim();
	validate(name, svg);
	entries.push(`\t${name}: ${JSON.stringify(svg)},`);
}

const generated = `// Generated by \`node scripts/build-friend-action-icons.mjs\`.
// Edit assets/icons/friend-actions/*.svg, then rerun that command.

export const FRIEND_ACTION_ICON_XML = {
${entries.join("\n")}
} as const;

export type FriendActionIconName = keyof typeof FRIEND_ACTION_ICON_XML;
`;

if (process.argv.includes("--check")) {
	let current = "";
	try {
		current = await readFile(outputPath, "utf8");
	} catch {}
	if (current !== generated) {
		console.error("Friend action icon registry is stale. Run node scripts/build-friend-action-icons.mjs");
		process.exitCode = 1;
	}
} else {
	await writeFile(outputPath, generated);
}
