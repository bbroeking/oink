def cmd_device(n: int, record_path: str) -> int:
    tpath = os.path.join(ROOT, "docs", "builds", "expectations", f"build-{n}-acceptance-template.json")
    if not os.path.exists(tpath):
        sys.exit(f"no acceptance template {rel(tpath)}")
    with open(tpath) as f:
        template = json.load(f)
    with open(record_path) as f:
        record = json.load(f)
    if str(record.get("build")) != str(n):
        sys.exit(f"record is for build {record.get('build')!r}, not {n}")
    checks, problems = evaluate_acceptance(template, record)
    ev = os.path.join(verification_dir(n), "device-acceptance.json")
    with open(ev, "w") as f:
        json.dump(record, f, indent=2)
        f.write("\n")
    fields = record.get("fields", {})
    rec = save(n, "device", checks, [ev], {"fields": fields, "template": rel(tpath)})
    print_rec("device", rec)
    return 0 if rec["status"] == "pass" else 1


# ── status / go ──────────────────────────────────────────────────────────────

def cmd_status(n: int) -> int:
    status = load_status(n)
    cand, cand_ok, problems = candidate_info(n)
    print(f"Build {n}: candidate {cand['candidate_commit']}  IPA {cand['ipa']}")
    print(f"  changelog {cand['changelog']}  recorded SHA-256 {cand['recorded_sha256']}")
    for r in ladder(status, cand_ok):
        rec = stage_record(status, r["rung"])
        when = f"  ({rec.get('at')})" if rec.get("at") else ""
        note = f"  {r.get('note')}" if r.get("note") else ""
        print(f"  {r['rung']:10} {r['status']}{when}{note}")
        if r["rung"] == "candidate" and problems:
            for p in problems:
                print(f"             - {p}")
        for c in (rec.get("details") or {}).get("checks", []):
            if c["status"] != "pass":
                print(f"             - [{c['status']}] {c['name']}: {c.get('detail', '')}")
    write_section(n, status, cand_ok)
    return 0


def cmd_go(n: int, by: str, decision: str, note: str) -> int:
    status = load_status(n)
    cand, cand_ok, _ = candidate_info(n)
    binary = stage_record(status, "binary")
    sha = (binary.get("details") or {}).get("sha256")
    if decision == "go" and not is_verified(status, cand_ok):
        pending = [r["rung"] + "=" + r["status"] for r in ladder(status, cand_ok)
                   if r["rung"] in STAGES + ["candidate"] and r["status"] != "pass"]
        sys.exit(f"refusing go: build {n} is not verified ({', '.join(pending)})")
    if decision == "go" and sha != cand["recorded_sha256"]:
        sys.exit("refusing go: the inspected IPA hash does not match the changelog's")
    details = {"decision": decision, "by": by, "note": note, "ipa_sha256": sha or cand["recorded_sha256"],
               "candidate_commit": (binary.get("details") or {}).get("candidate_commit") or cand["candidate_commit"]}
    ev = os.path.join(verification_dir(n), "go.json")
    with open(ev, "w") as f:
        json.dump({"at": now_iso(), **details}, f, indent=2)
        f.write("\n")
    rec = save(n, "go", [check(f"founder decision: {decision}", decision == "go", note)], [ev], details,
               status_override="pass" if decision == "go" else "fail")
    print(f"go: {decision} by {by}, bound to {details['ipa_sha256']} @ {details['candidate_commit']} ({rec['at']})")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("binary", "server", "sim", "status"):
        sub.add_parser(name).add_argument("build", type=int)
    d = sub.add_parser("device")
    d.add_argument("build", type=int)
    d.add_argument("--record", required=True, help="filled-in copy of the build's acceptance template")
    g = sub.add_parser("go")
    g.add_argument("build", type=int)
    g.add_argument("--by", required=True)
    g.add_argument("--decision", required=True, choices=["go", "no-go"])
    g.add_argument("--note", default="")
    a = ap.parse_args(argv)
    if a.cmd == "binary":
        return cmd_binary(a.build)
    if a.cmd == "server":
        return cmd_server(a.build)
    if a.cmd == "sim":
        return cmd_sim(a.build)
    if a.cmd == "device":
        return cmd_device(a.build, a.record)
    if a.cmd == "status":
        return cmd_status(a.build)
    return cmd_go(a.build, a.by, a.decision, a.note)


if __name__ == "__main__":
    sys.exit(main())
