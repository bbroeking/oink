BUNDLE_ID = "com.broeking.ttp"
EXPECTED_ASSOCIATED_DOMAINS = ["applinks:ticklethepig.com"]
APP_INPUTS = ["app", "components", "hooks", "utils", "constants", "features", "assets",
              "metro.config.js", "app.json", "package.json", "ios"]
SIM_DEVICE_NAME = "iPhone 16 Pro Max"
SIM_ALIVE_SECONDS = 20
QUERY_TIMEOUT_S = 90

STAGES = ["binary", "server", "sim", "device"]
LADDER = ["candidate"] + STAGES + ["verified", "go"]
STATUSES = ("pass", "fail", "pending")
ROW_RESULTS = ("pass", "fail", "pending", "waived")

SECTION_HEADING = "## Verification"
SECTION_MARKER = ("<!-- generated by scripts/release/promote_build.py from "
                  "artifacts/build-{n}/verification/status.json; rerun a stage to refresh, "
                  "do not edit by hand -->")
MARKER_PREFIX = "<!-- generated by scripts/release/promote_build.py"


# ── Pure helpers (unit-tested in test_promote_build.py) ──────────────────────

def now_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def rollup(checks: list[dict]) -> str:
    """A stage's status from its checks: any fail -> fail, any pending -> pending, else pass."""
    states = [c.get("status") for c in checks]
    if not states:
        return "pending"
    if "fail" in states:
        return "fail"
    if "pending" in states:
        return "pending"
    return "pass"


def check(name: str, ok: bool | None, detail: str = "") -> dict:
    """ok True -> pass, False -> fail, None -> pending."""
    return {"name": name, "status": "pending" if ok is None else ("pass" if ok else "fail"), "detail": detail}


def _is_number(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def values_match(expected, actual) -> bool:
    """Expectation value equality. Numbers compare numerically (a numeric string such as
    Postgres numeric's "1.5" counts as its number); dicts/lists compare recursively."""
    if isinstance(expected, bool) or isinstance(actual, bool):
        return isinstance(expected, bool) and isinstance(actual, bool) and expected == actual
    if _is_number(expected):
        if _is_number(actual):
            return float(expected) == float(actual)
        if isinstance(actual, str):
            try:
                return float(actual) == float(expected)
            except ValueError:
                return False
        return False
    if isinstance(expected, dict):
        return (isinstance(actual, dict) and set(expected) == set(actual)
                and all(values_match(expected[k], actual[k]) for k in expected))
    if isinstance(expected, list):
        return (isinstance(actual, list) and len(expected) == len(actual)
                and all(values_match(e, a) for e, a in zip(expected, actual)))
    return expected == actual


def migration_versions(filenames: list[str]) -> list[str]:
    """14-digit version prefixes of migration filenames (YYYYMMDDHHMMSS_name.sql)."""
    out = []
    for f in filenames:
        m = re.match(r"^(\d{14})_.*\.sql$", os.path.basename(f))
        if m:
            out.append(m.group(1))
    return sorted(set(out))


def evaluate_expectation(expect: dict, rows: list[dict], local_versions: list[str] | None = None) -> tuple[bool, str]:
    """Evaluate one expectation against the query's rows. Returns (ok, detail).

    Supported `expect` shapes (one key):
      {"row": {...}}           exactly one row; each named column matches
      {"rows": [...]}          the rows equal this list exactly (order matters)
      {"row_count": n}         the query returned n rows
      {"migrations_applied": {"held": [...], "held_must_be_unapplied": true}}
                               rows are [{version}]; every local migration file except
                               `held` is applied (and, by default, no held one is)
    """
    if not isinstance(expect, dict) or len(expect) != 1:
        return False, f"bad expectation (need exactly one key): {expect!r}"
    kind, want = next(iter(expect.items()))
    if kind == "row":
        if len(rows) != 1:
            return False, f"expected exactly 1 row, got {len(rows)}: {json.dumps(rows)[:300]}"
        row = rows[0]
        bad = {k: row.get(k, "<missing>") for k, v in want.items() if k not in row or not values_match(v, row[k])}
        if bad:
            return False, "mismatch: " + ", ".join(f"{k}={json.dumps(bad[k])} (want {json.dumps(want[k])})" for k in bad)
        return True, ", ".join(f"{k}={json.dumps(row[k])}" for k in want)
    if kind == "rows":
        ok = values_match(want, rows)
        return ok, (f"{len(rows)} rows as expected" if ok else f"got {json.dumps(rows)[:300]}, want {json.dumps(want)[:300]}")
    if kind == "row_count":
        ok = len(rows) == want
        return ok, f"{len(rows)} rows" + ("" if ok else f" (want {want})")
    if kind == "migrations_applied":
        if local_versions is None:
            return False, "no local migration list supplied"
        held = set((want or {}).get("held", []))
        held_must_be_unapplied = (want or {}).get("held_must_be_unapplied", True)
        applied = {str(r.get("version")) for r in rows}
        local = set(local_versions)
        missing = sorted(local - held - applied)
        held_applied = sorted(held & applied)
        remote_only = sorted(applied - local)
        parts = [f"{len(local - held)} expected, {len((local - held) & applied)} applied"]
        if missing:
            parts.append("NOT APPLIED: " + ", ".join(missing))
        if held_applied:
            parts.append("held but applied: " + ", ".join(held_applied))
        else:
            parts.append(f"held unapplied: {', '.join(sorted(held)) or 'none'}")
        if remote_only:
            parts.append(f"{len(remote_only)} applied with no local file")
        ok = not missing and not (held_must_be_unapplied and held_applied)
        return ok, "; ".join(parts)
    return False, f"unknown expectation kind {kind!r}"


def validate_readonly_sql(sql: str) -> str | None:
    """A static guard on top of the read-only transaction: one SELECT/WITH statement."""
    s = sql.strip()
    if not re.match(r"(?is)^(select|with)\b", s):
        return "must start with SELECT or WITH"
    if ";" in s:
        return "must be a single statement (no ';')"
    return None


def parse_query_output(stdout: str) -> list[dict]:
    """`supabase db query --linked` prints {"boundary", "rows": [...], "warning"}."""
    start = stdout.find("{")
    if start < 0:
        raise ValueError(f"no JSON in query output: {stdout[:200]!r}")
    data = json.loads(stdout[start:])
    rows = data.get("rows")
    if not isinstance(rows, list):
        raise ValueError(f"query output has no rows list: {stdout[:200]!r}")
    return rows


def strip_generated_section(text: str) -> str:
    """The changelog without the generated Verification section (so parsing never reads our own output)."""
    span = _section_span(text)
    if span and MARKER_PREFIX in text[span[0]:span[1]]:
        return text[:span[0]] + text[span[1]:]
    return text


def _section_span(text: str) -> tuple[int, int] | None:
    m = re.search(r"(?m)^## Verification[ \t]*\n", text)
    if not m:
        m = re.search(r"(?m)^## Verification[ \t]*\Z", text)
        if not m:
            return None
    nxt = re.search(r"(?m)^## (?!#)", text[m.end():])
    end = m.end() + nxt.start() if nxt else len(text)
    return m.start(), end


class HandWrittenSection(Exception):
    pass


def replace_verification_section(text: str, section: str) -> str:
    """Replace the generated `## Verification` section, or append one at the end.

    `section` is the complete section (heading + marker + body). A `## Verification`
    section WITHOUT the generator marker is hand-written evidence: refuse to overwrite it.
    """
    section = section.rstrip("\n") + "\n"
    span = _section_span(text)
    if span is None:
        return text.rstrip("\n") + "\n\n" + section
    start, end = span
    if MARKER_PREFIX not in text[start:end]:
        raise HandWrittenSection(
            "the changelog already has a hand-written '## Verification' section; rename it "
            "(e.g. '## Verification notes') so the generated one can be added")
    tail = text[end:]
    return text[:start] + section + ("\n" + tail if tail.strip() else "")


def parse_changelog(text: str) -> dict:
    """Candidate commit and recorded IPA SHA-256 from the hand-written part of a changelog."""
    body = strip_generated_section(text)
    commit = re.search(r"Candidate commit:\s*`([0-9a-f]{7,40})`", body)
    sha = re.search(r"SHA-256\s*`([0-9a-f]{64})`", body)
    return {"candidate_commit": commit.group(1) if commit else None,
            "recorded_sha256": sha.group(1) if sha else None}


def stage_record(status: dict, stage: str) -> dict:
    return (status.get("stages") or {}).get(stage) or {}


def ladder(status: dict, candidate_ok: bool) -> list[dict]:
    """The promotion ladder: candidate -> binary -> server -> sim -> device -> verified -> go."""
    rungs = [{"rung": "candidate", "status": "pass" if candidate_ok else "fail"}]
    for s in STAGES:
        rungs.append({"rung": s, "status": stage_record(status, s).get("status", "pending")})
    verified = candidate_ok and all(r["status"] == "pass" for r in rungs[1:])
    rungs.append({"rung": "verified", "status": "pass" if verified else "pending"})
    go = stage_record(status, "go")
    if not go:
        rungs.append({"rung": "go", "status": "pending"})
    else:
        decision = (go.get("details") or {}).get("decision")
        bound_sha = (go.get("details") or {}).get("ipa_sha256")
        binary_sha = (stage_record(status, "binary").get("details") or {}).get("sha256")
        if decision == "go" and (not verified or bound_sha != binary_sha):
            rungs.append({"rung": "go", "status": "fail", "note": "go no longer valid: not verified or the hash moved"})
        else:
            rungs.append({"rung": "go", "status": "pass" if decision == "go" else "fail", "note": decision})
    return rungs


def is_verified(status: dict, candidate_ok: bool) -> bool:
    return next(r for r in ladder(status, candidate_ok) if r["rung"] == "verified")["status"] == "pass"


def evaluate_acceptance(template: dict, record: dict) -> tuple[list[dict], list[str]]:
    """Merge a founder's acceptance record onto the template. Returns (checks, problems).

    Every template row must appear in the record. A row's result is pass | fail |
    pending | waived; waived (an accepted residual risk) needs a note, and counts as a pass.
    """
    problems = []
    for field in template.get("fields", {}):
        if not str(record.get("fields", {}).get(field, "")).strip():
            problems.append(f"missing field: {field}")
    by_id = {r.get("id"): r for r in record.get("rows", [])}
    checks = []
    for row in template.get("rows", []):
        rid = row["id"]
        got = by_id.get(rid)
        result = (got or {}).get("result", "pending")
        note = ((got or {}).get("notes") or "").strip()
        if result not in ROW_RESULTS:
            problems.append(f"{rid}: result {result!r} is not one of {ROW_RESULTS}")
            result = "fail"
        if result == "waived" and not note:
            problems.append(f"{rid}: waived without a note (say who accepted the risk and why)")
            result = "pending"
        status = {"pass": "pass", "waived": "pass", "fail": "fail", "pending": "pending"}[result]
        detail = result + (f": {note}" if note else "")
        checks.append({"name": f"{rid}", "status": status, "detail": detail})
    unknown = sorted(set(by_id) - {r["id"] for r in template.get("rows", [])})
    if unknown:
        problems.append("rows not in the template: " + ", ".join(unknown))
    if problems:
        checks.append({"name": "record complete", "status": "pending", "detail": "; ".join(problems)})
    return checks, problems


def render_section(n: int, status: dict, candidate_ok: bool) -> str:
    rungs = ladder(status, candidate_ok)
    lines = [SECTION_HEADING, "", SECTION_MARKER.format(n=n), ""]
    lines.append("Promotion ladder ([process](../release/promotion.md)): "
                 + " → ".join(f"{r['rung']} **{r['status']}**" for r in rungs) + ".")
    cand = status.get("candidate") or {}
    if cand:
        lines.append("")
        lines.append(f"Candidate: commit `{cand.get('candidate_commit')}`, IPA SHA-256 `{cand.get('recorded_sha256')}` "
                     "(as recorded in Release status). Evidence under `artifacts/build-%d/verification/` "
                     "(gitignored, local)." % n)
    for s in STAGES + ["go"]:
        rec = stage_record(status, s)
        lines.append("")
        if not rec:
            lines.append(f"**{s}**: pending (not run).")
            continue
        lines.append(f"**{s}**: {rec.get('status')} at {rec.get('at')}.")
        if s == "go":
            d = rec.get("details") or {}
            lines.append(f"- Decision **{d.get('decision')}** by {d.get('by')}, bound to IPA SHA-256 "
                         f"`{d.get('ipa_sha256')}` and candidate `{d.get('candidate_commit')}`. {d.get('note') or ''}".rstrip())
            continue
        for c in (rec.get("details") or {}).get("checks", []):
            detail = c.get("detail") or ""
            detail = detail.replace("|", "\\|").replace("\n", " ")
            lines.append(f"- {c['status']}: {c['name']}" + (f" ({detail})" if detail else ""))
        ev = rec.get("evidence") or []
        if ev:
            lines.append("- evidence: " + ", ".join(f"`{e}`" for e in ev))
    return "\n".join(lines) + "\n"


# ── Paths and state ──────────────────────────────────────────────────────────

def rel(path: str) -> str:
    return os.path.relpath(path, ROOT)


def verification_dir(n: int) -> str:
    d = os.path.join(ROOT, "artifacts", f"build-{n}", "verification")
    os.makedirs(d, exist_ok=True)
    return d


def changelog_path(n: int) -> str:
    hits = sorted(glob.glob(os.path.join(ROOT, "docs", "builds", f"*-build-{n}.md")))
    if not hits:
        sys.exit(f"no changelog docs/builds/*-build-{n}.md")
    # Several dated files can share a number (a planned build never built); the newest is the candidate.
    return hits[-1]


def load_status(n: int) -> dict:
    p = os.path.join(verification_dir(n), "status.json")
    if os.path.exists(p):
        with open(p) as f:
            return json.load(f)
    return {"build": n, "stages": {}}


def candidate_info(n: int) -> tuple[dict, bool, list[str]]:
    """The candidate rung: changelog records commit + SHA-256, the commit exists, the IPA exists."""
    cl = changelog_path(n)
    with open(cl) as f:
        info = parse_changelog(f.read())
    info["changelog"] = rel(cl)
    ipa = os.path.join(ROOT, "artifacts", f"build-{n}", f"build-{n}.ipa")
    info["ipa"] = rel(ipa)
    problems = []
    if not info["candidate_commit"]:
        problems.append("changelog records no 'Candidate commit: `<sha>`'")
    elif run(["git", "cat-file", "-e", info["candidate_commit"] + "^{commit}"]).returncode != 0:
        problems.append(f"candidate commit {info['candidate_commit']} does not exist")
    if not info["recorded_sha256"]:
        problems.append("changelog records no 'SHA-256 `<hash>`'")
    if not os.path.exists(ipa):
        problems.append(f"IPA missing: {rel(ipa)}")
    return info, not problems, problems


def save(n: int, stage: str, checks: list[dict], evidence: list[str], extra: dict | None = None,
         status_override: str | None = None) -> dict:
    status = load_status(n)
    cand, cand_ok, _ = candidate_info(n)
    status["build"] = n
    status["candidate"] = {k: cand[k] for k in ("candidate_commit", "recorded_sha256", "changelog", "ipa")}
    details = {"checks": checks}
    details.update(extra or {})
    rec = {"status": status_override or rollup(checks), "at": now_iso(),
           "evidence": [rel(e) if os.path.isabs(e) else e for e in evidence], "details": details}
    status.setdefault("stages", {})[stage] = rec
    p = os.path.join(verification_dir(n), "status.json")
    with open(p, "w") as f:
        json.dump(status, f, indent=2, sort_keys=False)
        f.write("\n")
    write_section(n, status, cand_ok)
    return rec


def write_section(n: int, status: dict, cand_ok: bool) -> None:
    cl = changelog_path(n)
    with open(cl) as f:
        text = f.read()
    new = replace_verification_section(text, render_section(n, status, cand_ok))
    if new != text:
        with open(cl, "w") as f:
            f.write(new)


def run(cmd: list[str], timeout: int | None = None, **kw) -> subprocess.CompletedProcess:
    """Run a command; a hung tool (simctl, idb, the CLI) is cut off by the perl alarm wrapper."""
    if timeout:
        cmd = ["perl", "-e", f"alarm {int(timeout)}; exec @ARGV"] + cmd
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, **kw)


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def print_rec(stage: str, rec: dict) -> None:
    print(f"{stage}: {rec['status'].upper()}")
    for c in rec["details"].get("checks", []):
        print(f"  [{c['status']:7}] {c['name']}" + (f" - {c['detail']}" if c.get("detail") else ""))
    for e in rec.get("evidence", []):
        print(f"  evidence: {e}")


# ── binary ───────────────────────────────────────────────────────────────────

def cmd_binary(n: int) -> int:
    cand, cand_ok, cand_problems = candidate_info(n)
    vdir = verification_dir(n)
    ipa = os.path.join(ROOT, cand["ipa"])
    checks: list[dict] = []
    report: dict = {"ipa": cand["ipa"]}
    if not os.path.exists(ipa):
        checks.append(check("IPA present", False, cand["ipa"]))
        rec = save(n, "binary", checks, [])
        print_rec("binary", rec)
        return 1

    sha = sha256_file(ipa)
    report["sha256"] = sha
    report["size_bytes"] = os.path.getsize(ipa)
    checks.append(check("SHA-256 matches the changelog", sha == cand["recorded_sha256"],
                        f"{sha}" + ("" if sha == cand["recorded_sha256"] else f" vs recorded {cand['recorded_sha256']}")))

    work = tempfile.mkdtemp(prefix=f"ttp-build-{n}-")
    try:
        r = run(["unzip", "-q", ipa, "-d", work], timeout=300)
        apps = glob.glob(os.path.join(work, "Payload", "*.app"))
        if r.returncode != 0 or not apps:
            checks.append(check("IPA unzips to Payload/*.app", False, r.stderr.strip()[:300]))
        else:
            app = apps[0]
            with open(os.path.join(app, "Info.plist"), "rb") as f:
                info = plistlib.load(f)
            keys = ["CFBundleShortVersionString", "CFBundleVersion", "CFBundleIdentifier", "MinimumOSVersion"]
            report["info_plist"] = {k: info.get(k) for k in keys}
            want_version = None
            if cand["candidate_commit"]:
                g = run(["git", "show", f"{cand['candidate_commit']}:app.json"])
                if g.returncode == 0:
                    want_version = json.loads(g.stdout).get("expo", {}).get("version")
            short = info.get("CFBundleShortVersionString")
            checks.append(check("CFBundleShortVersionString = app.json version at the candidate",
                                want_version is not None and short == want_version, f"{short} (app.json {want_version})"))
            checks.append(check(f"CFBundleVersion == {n}", str(info.get("CFBundleVersion")) == str(n),
                                str(info.get("CFBundleVersion"))))
            checks.append(check(f"bundle id {BUNDLE_ID}", info.get("CFBundleIdentifier") == BUNDLE_ID,
                                str(info.get("CFBundleIdentifier"))))
            min_os = info.get("MinimumOSVersion")
            with open(os.path.join(ROOT, cand["changelog"])) as f:
                rec_min = re.search(r"MinimumOSVersion\s+([\d.]+)", strip_generated_section(f.read()))
            checks.append(check("MinimumOSVersion" + (" matches the changelog" if rec_min else " present"),
                                bool(min_os) and (not rec_min or rec_min.group(1) == min_os),
                                f"{min_os}" + (f" (recorded {rec_min.group(1)})" if rec_min else "")))

            e = subprocess.run(["codesign", "-d", "--entitlements", ":-", app], capture_output=True)
            try:
                ent = plistlib.loads(e.stdout) if e.stdout.strip() else {}
            except Exception as ex:  # noqa: BLE001
                ent = {}
                report["entitlements_error"] = str(ex)
            report["entitlements"] = {k: v for k, v in ent.items() if isinstance(v, (str, bool, list, int))}
            checks.append(check("aps-environment production", ent.get("aps-environment") == "production",
                                str(ent.get("aps-environment"))))
            checks.append(check("get-task-allow false", ent.get("get-task-allow") is False,
                                str(ent.get("get-task-allow"))))
            domains = ent.get("com.apple.developer.associated-domains") or []
            checks.append(check("associated domains", all(d in domains for d in EXPECTED_ASSOCIATED_DOMAINS),
                                ", ".join(domains) or "none"))
            v = run(["codesign", "--verify", "--deep", "--strict", app], timeout=600)
            report["codesign_verify"] = {"exit": v.returncode, "output": (v.stdout + v.stderr).strip()[:1000]}
            checks.append(check("codesign --verify --deep --strict", v.returncode == 0,
                                "OK" if v.returncode == 0 else (v.stdout + v.stderr).strip()[:300]))
            frames = [p for p in glob.glob(os.path.join(app, "**", "*.png"), recursive=True)
                      if "sprites/costumes" in p.replace(os.sep, "/")]
            report["costume_frames_in_bundle"] = len(frames)
    finally:
        shutil.rmtree(work, ignore_errors=True)

    # Provenance.
    commit = cand["candidate_commit"]
    if not commit or not cand_ok and any("does not exist" in p for p in cand_problems):
        checks.append(check("candidate commit exists", False, "; ".join(cand_problems)))
    else:
        full = run(["git", "rev-parse", commit]).stdout.strip()
        report["candidate_commit_full"] = full
        checks.append(check("candidate commit exists", True, full))
        anc = run(["git", "merge-base", "--is-ancestor", commit, "HEAD"]).returncode == 0
        head = run(["git", "rev-parse", "--short", "HEAD"]).stdout.strip()
        checks.append(check("candidate is an ancestor of HEAD", anc, f"HEAD {head}"))
        d = run(["git", "diff", "--stat", commit, "HEAD", "--"] + APP_INPUTS)
        stat = d.stdout.strip()
        report["app_input_diff_stat"] = stat
        changed = [ln.split("|")[0].strip() for ln in stat.splitlines() if "|" in ln]
        checks.append(check("app inputs unchanged candidate..HEAD" if not changed else
                            "app inputs changed candidate..HEAD (listed; the IPA is the candidate's)",
                            d.returncode == 0,
                            "empty" if not changed else ", ".join(changed)))

    ev = os.path.join(vdir, "binary.json")
    with open(ev, "w") as f:
        json.dump(report, f, indent=2)
        f.write("\n")
    rec = save(n, "binary", checks, [ev], {"sha256": report.get("sha256"),
                                           "candidate_commit": report.get("candidate_commit_full", commit)})
    print_rec("binary", rec)
    return 0 if rec["status"] == "pass" else 1


