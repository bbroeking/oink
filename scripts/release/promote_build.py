#!/usr/bin/env python3
"""Promote an iOS build to verified: candidate -> binary -> server -> sim -> device -> verified -> go.

Each stage writes artifacts/build-<N>/verification/status.json and regenerates
the generated `## Verification` section of the build's changelog in docs/builds/.
Process doc: docs/release/promotion.md. Stdlib only.

  python3 scripts/release/promote_build.py binary 198
  python3 scripts/release/promote_build.py server 198      # read-only production checks
  python3 scripts/release/promote_build.py sim 198
  python3 scripts/release/promote_build.py device 198 --record path/to/acceptance.json
  python3 scripts/release/promote_build.py status 198
  python3 scripts/release/promote_build.py go 198 --by "Brian Broeking" --decision go --note "..."

Every production query runs inside `set transaction read only;` and must be a
single SELECT/WITH statement; this tool never writes to the database.
"""
