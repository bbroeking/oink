def run_readonly_query(sql: str) -> list[dict]:
    script = ('set -a; source .env.supabase; set +a; '
              f'exec perl -e "alarm {QUERY_TIMEOUT_S}; exec @ARGV" npx supabase db query --linked "$1"')
    r = subprocess.run(["bash", "-c", script, "_", "set transaction read only; " + sql],
                       cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"exit {r.returncode}: {(r.stderr or r.stdout).strip()[-400:]}")
    return parse_query_output(r.stdout)


def cmd_server(n: int) -> int:
    path = os.path.join(ROOT, "docs", "builds", "expectations", f"build-{n}.json")
    if not os.path.exists(path):
        sys.exit(f"no expectations file {rel(path)}")
    if not os.path.exists(os.path.join(ROOT, ".env.supabase")):
        sys.exit(".env.supabase missing (needed for npx supabase db query --linked)")
    with open(path) as f:
        expectations = json.load(f)
    local_versions = migration_versions(os.listdir(os.path.join(ROOT, "supabase", "migrations")))
    checks, results = [], []
    for exp in expectations:
        name, sql, expect = exp["name"], exp["sql"], exp["expect"]
        bad = validate_readonly_sql(sql)
        entry = {"name": name, "sql": sql, "expect": expect}
        if bad:
            ok, detail = False, f"refused: {bad}"
        else:
            try:
                rows = run_readonly_query(sql)
                entry["rows"] = rows if len(rows) <= 50 else {"count": len(rows), "first": rows[:5]}
                ok, detail = evaluate_expectation(expect, rows, local_versions)
            except Exception as ex:  # noqa: BLE001
                ok, detail = False, f"query error: {ex}"
        entry.update({"ok": ok, "detail": detail})
        results.append(entry)
        checks.append(check(name, ok, detail))
        print(f"  [{'pass' if ok else 'FAIL':4}] {name}: {detail}")
    ev = os.path.join(verification_dir(n), "server.json")
    with open(ev, "w") as f:
        json.dump({"expectations": rel(path), "at": now_iso(), "results": results}, f, indent=2)
        f.write("\n")
    rec = save(n, "server", checks, [ev, rel(path)])
    print_rec("server", rec)
    return 0 if rec["status"] == "pass" else 1


# ── sim ──────────────────────────────────────────────────────────────────────

SIGNED_OUT_LABELS = ("Sign in with Apple", "or use email", "Meet Rosie")
TAB_LABELS = ("Barn", "Friends", "Season", "Shop", "Me")
SYSTEM_DIALOG_HINTS = ("Apple Account", "Password", "Sign In to", "Not Now")
APP_DISPLAY_NAME = "Tickle the Pig"


def find_device(name: str) -> dict | None:
    r = run(["xcrun", "simctl", "list", "devices", "available", "-j"], timeout=60)
    devices = [d for ds in json.loads(r.stdout).get("devices", {}).values() for d in ds if d.get("name") == name]
    devices.sort(key=lambda d: d.get("state") != "Booted")
    return devices[0] if devices else None


def idb_path() -> str | None:
    return shutil.which("idb") or (os.path.expanduser("~/.local/bin/idb")
                                   if os.path.exists(os.path.expanduser("~/.local/bin/idb")) else None)


def idb_elements(idb: str, udid: str) -> list[dict]:
    r = run([idb, "ui", "describe-all", "--udid", udid], timeout=60)
    try:
        return json.loads(r.stdout)
    except ValueError:
        return []


def find_label(elements: list[dict], prefix: str) -> dict | None:
    for e in elements:
        label = (e.get("AXLabel") or "").strip()
        if label == prefix or label.startswith(prefix + ",") or label.startswith(prefix + " "):
            return e
    return None


def idb_tap(idb: str, udid: str, el: dict) -> None:
    fr = el["frame"]
    x, y = fr["x"] + fr["width"] / 2, fr["y"] + fr["height"] / 2
    run([idb, "ui", "tap", f"{x:.0f}", f"{y:.0f}", "--udid", udid], timeout=30)


def screenshot(udid: str, path: str) -> bool:
    return run(["xcrun", "simctl", "io", udid, "screenshot", path], timeout=60).returncode == 0


def app_is_frontmost(elements: list[dict]) -> bool:
    """The tree's root is this app (a system alert replaces it with a blank or SpringBoard root)."""
    return bool(elements) and elements[0].get("type") == "Application" and \
        (elements[0].get("AXLabel") or "").strip() == APP_DISPLAY_NAME


def dismiss_interstitials(idb: str, udid: str, limit: int = 6) -> tuple[list[dict], list[str]]:
    """Tap the app's own "Got it" (achievement / reward / guide popups queue on launch and hide
    the tab bar from accessibility). Only while the app itself is frontmost and no system-dialog
    text is on screen; never anything else."""
    dismissed = []
    els = idb_elements(idb, udid)
    for _ in range(limit):
        labels = [(e.get("AXLabel") or "").strip() for e in els]
        if not app_is_frontmost(els) or any(h in lb for lb in labels for h in SYSTEM_DIALOG_HINTS):
            break
        if sum(1 for t in TAB_LABELS if find_label(els, t)) >= 3:
            break
        got = next((e for e in els if e.get("type") == "Button" and (e.get("AXLabel") or "").strip() == "Got it"), None)
        if not got:
            break
        title = next((lb for lb in labels[1:] if lb and lb not in ("Close", "Got it")), "")
        idb_tap(idb, udid, got)
        dismissed.append(title)
        time.sleep(2)
        els = idb_elements(idb, udid)
    return els, dismissed


def signed_in_smoke(idb: str, udid: str, vdir: str) -> tuple[list[dict], list[str]]:
    """Home, the Barn-button fan (Riddle row), Shop, Season, Closet. Taps only app
    elements found by label; never types, never touches a system dialog."""
    checks, evidence = [], []

    def shot(name: str) -> str:
        p = os.path.join(vdir, f"sim-{name}.png")
        screenshot(udid, p)
        evidence.append(p)
        return p

    def tab(label: str) -> bool:
        el = find_label(idb_elements(idb, udid), label)
        if not el:
            return False
        idb_tap(idb, udid, el)
        time.sleep(3)
        return True

    if tab("Barn"):
        shot("home")
        checks.append(check("Home (Barn tab)", True, "screenshot"))
        plus = find_label(idb_elements(idb, udid), "More actions")
        if plus:
            idb_tap(idb, udid, plus)
            time.sleep(2)
            els = idb_elements(idb, udid)
            riddle = find_label(els, "Riddle")
            shot("barn-fan")
            checks.append(check("Barn-button fan has the Riddle row", riddle is not None,
                                "Riddle row present" if riddle else "no 'Riddle' row in the fan"))
            close = find_label(els, "Close")
            if close:
                idb_tap(idb, udid, close)
                time.sleep(1)
        else:
            checks.append(check("Barn-button fan has the Riddle row", None, "no 'More actions' button found"))
    else:
        checks.append(check("Home (Barn tab)", None, "Barn tab not found"))
    for name in ("Shop", "Season"):
        ok = tab(name)
        heading = ""
        if ok:
            shot(name.lower())
            heading = next(((e.get("AXLabel") or "").strip() for e in idb_elements(idb, udid)
                            if e.get("type") == "Heading"), "")
        checks.append(check(f"{name} tab", True if ok else None,
                            (f"heading '{heading}'" if heading else "screenshot") if ok else f"{name} tab not found"))
    # The Closet is the Shop's own rack since the one-room store ("Everything", owned filter,
    # under the fitting-room slots); older builds hung a "Closet" sign. Scroll, never filter.
    closet = None
    if tab("Shop"):
        els = idb_elements(idb, udid)
        sign = find_label(els, "Closet")
        if sign:
            idb_tap(idb, udid, sign)
            time.sleep(3)
            closet = "Closet sign"
        elif find_label(els, "Everything"):
            # A fling from the chalkboard (not a pressable) rides momentum down into the owned
            # rack; then require owned/wearing tiles ON SCREEN (the tree also lists off-screen rows).
            run([idb, "ui", "swipe", "100", "620", "100", "120", "--duration", "0.2", "--udid", udid], timeout=30)
            time.sleep(3)
            els = idb_elements(idb, udid)
            height = els[0]["frame"]["height"] if els else 0
            owned = [e for e in els if e.get("type") == "Button"
                     and re.search(r", (owned|wearing)$", (e.get("AXLabel") or "").strip())
                     and 0 <= e["frame"]["y"] < height - 150]
            closet = f"owned rack on screen, {len(owned)} tiles" if len(owned) >= 3 else None
        if closet:
            shot("closet")
    checks.append(check("Closet", True if closet else None,
                        closet or "neither a Closet sign nor the owned rack (Everything) reached on Shop"))
    return checks, evidence


def cmd_sim(n: int) -> int:
    vdir = verification_dir(n)
    checks, evidence = [], []
    extra: dict = {}
    apps = glob.glob(os.path.join(ROOT, "artifacts", f"build-{n}-sim", "app", "*.app"))
    if not apps:
        checks.append(check("simulator .app present", False, f"no artifacts/build-{n}-sim/app/*.app"))
        rec = save(n, "sim", checks, [])
        print_rec("sim", rec)
        return 1
    app = apps[0]
    with open(os.path.join(app, "Info.plist"), "rb") as f:
        art_info = plistlib.load(f)
    art_short = art_info.get("CFBundleShortVersionString")
    exe = os.path.join(app, art_info.get("CFBundleExecutable", ""))
    art_exe_sha = sha256_file(exe) if os.path.isfile(exe) else None
    extra["artifact"] = {"app": rel(app), "short_version": art_short,
                         "bundle_version": art_info.get("CFBundleVersion"), "executable_sha256": art_exe_sha}

    dev = find_device(SIM_DEVICE_NAME)
    if not dev:
        checks.append(check(f"{SIM_DEVICE_NAME} simulator available", False, "not in simctl list"))
        rec = save(n, "sim", checks, [], extra)
        print_rec("sim", rec)
        return 1
    udid = dev["udid"]
    extra["device"] = {"name": SIM_DEVICE_NAME, "udid": udid}
    if dev.get("state") != "Booted":
        run(["xcrun", "simctl", "boot", udid], timeout=120)
    booted = run(["xcrun", "simctl", "bootstatus", udid, "-b"], timeout=300).returncode == 0
    checks.append(check(f"{SIM_DEVICE_NAME} booted", booted, udid))
    if not booted:
        rec = save(n, "sim", checks, [], extra)
        print_rec("sim", rec)
        return 1

    # Install unless the installed app is this artifact (same short version and same executable:
    # a dev client shares the bundle id and version, and is not the release binary).
    c = run(["xcrun", "simctl", "get_app_container", udid, BUNDLE_ID, "app"], timeout=60)
    installed = c.stdout.strip() if c.returncode == 0 else ""
    reason = None
    if not installed:
        reason = "not installed"
    else:
        with open(os.path.join(installed, "Info.plist"), "rb") as f:
            inst_info = plistlib.load(f)
        inst_exe = os.path.join(installed, inst_info.get("CFBundleExecutable", ""))
        if inst_info.get("CFBundleShortVersionString") != art_short:
            reason = f"installed version {inst_info.get('CFBundleShortVersionString')} != {art_short}"
        elif not os.path.isfile(inst_exe) or sha256_file(inst_exe) != art_exe_sha:
            reason = "installed executable differs from the artifact (dev client or older build)"
    if reason:
        i = run(["xcrun", "simctl", "install", udid, app], timeout=600)
        checks.append(check("release-identical simulator app installed", i.returncode == 0,
                            f"installed ({reason})" if i.returncode == 0 else i.stderr.strip()[:300]))
        if i.returncode != 0:
            rec = save(n, "sim", checks, [], extra)
            print_rec("sim", rec)
            return 1
    else:
        checks.append(check("release-identical simulator app installed", True,
                            f"already installed: {art_short}, executable matches the artifact"))

    started = time.time()
    la = run(["xcrun", "simctl", "launch", "--terminate-running-process", udid, BUNDLE_ID], timeout=120)
    m = re.search(r":\s*(\d+)\s*$", la.stdout.strip())
    pid = int(m.group(1)) if m else None
    checks.append(check(f"launch {BUNDLE_ID}", la.returncode == 0 and pid is not None,
                        f"pid {pid}" if pid else (la.stderr or la.stdout).strip()[:300]))
    if pid is None:
        rec = save(n, "sim", checks, [], extra)
        print_rec("sim", rec)
        return 1
    time.sleep(SIM_ALIVE_SECONDS)
    lc = run(["xcrun", "simctl", "spawn", udid, "launchctl", "list"], timeout=60)
    live_pid = None
    for ln in lc.stdout.splitlines():
        if f"UIKitApplication:{BUNDLE_ID}" in ln:
            first = ln.split()[0]
            live_pid = int(first) if first.isdigit() else None
    crash_logs = [p for p in glob.glob(os.path.expanduser("~/Library/Logs/DiagnosticReports/TicklethePig*.ips"))
                  if os.path.getmtime(p) >= started - 1]
    alive = live_pid == pid and not crash_logs
    checks.append(check(f"alive after {SIM_ALIVE_SECONDS} s (no crash)", alive,
                        f"pid {live_pid}" + (f"; crash reports: {', '.join(crash_logs)}" if crash_logs else "")
                        + ("" if live_pid == pid else f" (launched {pid})")))
    p = os.path.join(vdir, "sim-launch.png")
    if screenshot(udid, p):
        evidence.append(p)

    idb = idb_path()
    if not idb:
        checks.append(check("signed-in smoke", None, "needs founder sign-in (idb not installed, cannot drive the app)"))
    elif alive:
        els, dismissed = dismiss_interstitials(idb, udid)
        if dismissed:
            extra["interstitials_dismissed"] = dismissed
        labels = [(e.get("AXLabel") or "").strip() for e in els]
        extra["screen_labels"] = [label for label in labels if label][:40]
        signed_out = any(find_label(els, s) for s in SIGNED_OUT_LABELS)
        signed_in = sum(1 for t in TAB_LABELS if find_label(els, t)) >= 3
        dialog = [label for label in labels if any(h in label for h in SYSTEM_DIALOG_HINTS)]
        if signed_in and not dialog:
            sc, sev = signed_in_smoke(idb, udid, vdir)
            checks.extend(sc)
            evidence.extend(sev)
        else:
            why = ("signed out (welcome screen)" if signed_out else
                   "a system dialog is up" if dialog else
                   "sign-in state not detectable from the accessibility tree (a system dialog may cover the app)")
            checks.append(check("signed-in smoke (Home, Barn fan + Riddle, Shop, Season, Closet)", None,
                                f"needs founder sign-in: {why}"))
    ev = os.path.join(vdir, "sim.json")
    with open(ev, "w") as f:
        json.dump({"at": now_iso(), "checks": checks, **extra}, f, indent=2)
        f.write("\n")
    rec = save(n, "sim", checks, evidence + [ev], extra)
    print_rec("sim", rec)
    return 0 if rec["status"] != "fail" else 1


