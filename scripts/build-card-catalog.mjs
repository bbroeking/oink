import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "docs/marketing/trading-cards/base-set-84/cards.mjs");
const outputPath = resolve(root, "features/cards/data/catalog.generated.ts");
const artOutputPath = resolve(root, "features/cards/data/cardArt.ts");
const source = await import(pathToFileURL(sourcePath).href);

if (source.CARDS.length !== source.SET_META.cardCount) {
  throw new Error(`Expected ${source.SET_META.cardCount} cards, found ${source.CARDS.length}`);
}

const ids = new Set(source.CARDS.map((card) => card.id));
const numbers = new Set(source.CARDS.map((card) => card.number));
if (ids.size !== source.CARDS.length || numbers.size !== source.CARDS.length) {
  throw new Error("Card IDs and numbers must be unique");
}

const banner = `// Generated by scripts/build-card-catalog.mjs from\n// docs/marketing/trading-cards/base-set-84/cards.mjs. Do not edit by hand.\n`;
const contents = `${banner}import type { CardCatalogEntry, CardSetMeta } from "../domain/catalog";\n\nexport const CARD_SET = ${JSON.stringify(source.SET_META, null, 2)} as const satisfies CardSetMeta;\n\nexport const CARD_CATALOG = ${JSON.stringify(source.CARDS, null, 2)} as const satisfies readonly CardCatalogEntry[];\n`;
await writeFile(outputPath, contents);

const artEntries = source.CARDS.map(
  (card) => `  ${JSON.stringify(card.id)}: require(${JSON.stringify(`../../../${card.art}`)}),`,
).join("\n");
await writeFile(
  artOutputPath,
  `${banner}import type { ImageSourcePropType } from "react-native";\n\nexport const cardArtSources = {\n${artEntries}\n} as const satisfies Record<string, ImageSourcePropType>;\n`,
);

console.log(`Wrote ${source.CARDS.length} cards to ${outputPath} and ${artOutputPath}`);
