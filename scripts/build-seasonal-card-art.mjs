import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contentPath = join(root, "docs/design/halloween-2026/content.json");
const assetDir = join(root, "assets/images/trading-cards/halloween-2026");
const outputPath = join(root, "features/cards/data/seasonalCardArt.ts");
const checkOnly = process.argv.includes("--check");
const requireComplete = process.argv.includes("--require-complete");
const supportedFlags = new Set(["--check", "--require-complete"]);
for (const argument of process.argv.slice(2)) {
  if (!supportedFlags.has(argument)) throw new Error(`Unknown flag: ${argument}`);
}

const content = JSON.parse(readFileSync(contentPath, "utf8"));
if (!Array.isArray(content.unlockCards) || content.unlockCards.length === 0) {
  throw new Error("Halloween content has no unlockCards array");
}

const items = [...(Array.isArray(content.wearables) ? content.wearables : []), ...(Array.isArray(content.backgrounds) ? content.backgrounds : [])];
const itemById = new Map(items.map((item) => [item.id, item]));
const records = content.unlockCards.map((card, index) => {
  if (!card || typeof card.id !== "string" || typeof card.unlocks !== "string") {
    throw new Error(`Invalid unlock card at index ${index}`);
  }
  const item = itemById.get(card.unlocks);
  if (!item || item.cardId !== card.id) throw new Error(`Missing item mapping for unlock card: ${card.id}`);
  const cardArtVersion = item.cardArtVersion ?? 1;
  if (!Number.isInteger(cardArtVersion) || cardArtVersion < 1) {
    throw new Error(`Invalid cardArtVersion for ${item.id}: ${String(cardArtVersion)}`);
  }
  const number = String(index + 1).padStart(3, "0");
  const filename = `${number}-${card.unlocks.replaceAll("_", "-")}-card-v${cardArtVersion}.png`;
  return { cardId: card.id, filename, exists: existsSync(join(assetDir, filename)) };
});

const missing = records.filter((record) => !record.exists);
const registrations = records.filter((record) => record.exists).map((record) =>
  `  ${record.cardId}: require("../../../assets/images/trading-cards/halloween-2026/${record.filename}"),`
).join("\n");
const output = `// Generated by scripts/build-seasonal-card-art.mjs from
// docs/design/halloween-2026/content.json. Do not edit require registrations by hand.
import type { ImageSourcePropType } from "react-native";

export interface SeasonalCardConceptArt {
  background: string;
  accent: string;
  glyph: string;
  label: string;
}

/** Static fallback used until reviewed card illustrations are checked in. */
export const SPOOKY_SNOUTS_CONCEPT_ART: Readonly<Record<string, SeasonalCardConceptArt>> = {
  halloween_2026_card_moonbrew_witch_hat: { background: "#2d2146", accent: "#efb24b", glyph: "☾", label: "Moonbrew Witch Hat concept" },
  halloween_2026_card_hedge_broom: { background: "#34452f", accent: "#d8a45e", glyph: "✦", label: "Hedge Broom concept" },
  halloween_2026_card_lantern_porch_bg: { background: "#563044", accent: "#f29a44", glyph: "⌂", label: "Lantern Porch concept" },
};

/** Reviewed raster card illustrations checked into the bundle. */
export const SPOOKY_SNOUTS_ART_SOURCES: Readonly<Record<string, ImageSourcePropType>> = {
${registrations}
};
`;

if (requireComplete && missing.length > 0) {
  console.error(`Missing ${missing.length}/${records.length} seasonal card raster files:`);
  for (const record of missing) console.error(`- ${record.filename}`);
  process.exitCode = 1;
} else if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error(`${relative(root, outputPath)} is stale; run node scripts/build-seasonal-card-art.mjs`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, output);
  console.log(`Registered ${records.length - missing.length}/${records.length} seasonal card raster files.`);
  if (missing.length > 0) console.log(`${missing.length} cards continue to use truthful concept/missing-art fallbacks.`);
}
