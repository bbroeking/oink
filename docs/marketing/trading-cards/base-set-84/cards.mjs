const generatedPrintArt = (id) =>
  GENERATED_ART[id]?.replace(/-v(\d+)\.png$/, "-print-v$1.png");

const card = (number, id, name, type, rarity, fields) => ({
  number: String(number).padStart(3, "0"),
  id,
  name,
  type,
  rarity,
  ...fields,
});

const legend = (
  number,
  id,
  name,
  favoredStyles,
  abilityName,
  text,
  flavor,
  art,
  identity,
) =>
  card(number, id, name, "legend", "legendary", {
    legend: true,
    startsOutsideDeck: true,
    fullArt: true,
    startingCheer: 12,
    favoredStyles,
    abilityName,
    ...identity,
    text,
    flavor,
    identityArt: art,
    art: `assets/images/trading-cards/full-art/${id.replace("legend_", "")}-full-art-v1.png`,
    artStatus: "ready",
    source: "game",
  });

