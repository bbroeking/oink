const unit = (
  number,
  id,
  name,
  type,
  rarity,
  rank,
  style,
  bash,
  hearts,
  text,
  training,
  flavor,
  art = null,
  source = "card-original",
  artStatus = "needs-illustration",
) =>
  card(number, id, name, type, rarity, {
    rank,
    style,
    bash,
    hearts,
    text,
    training,
    flavor,
    art: art ?? generatedPrintArt(id) ?? null,
    artStatus: GENERATED_ART[id] ? "ready" : artStatus,
    source,
  });

